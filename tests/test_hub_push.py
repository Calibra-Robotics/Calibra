"""Tests for pushing Calibra cards to a HuggingFace Hub dataset README."""

from __future__ import annotations

import sys
import types
from unittest.mock import MagicMock

import pytest

from calibra.card import _CARD_END, _CARD_START, merge_card_into_readme, push_to_hub

CARD = "## Dataset Quality Report (Calibra v0.12.0)\n\nbody\n\n---\n_Generated by [Calibra](https://x) v0.12.0_\n"


def test_merge_into_empty_readme():
    out = merge_card_into_readme("", CARD)
    assert out.startswith(_CARD_START)
    assert out.rstrip().endswith(_CARD_END)


def test_merge_appends_and_keeps_existing_content():
    readme = "---\nlicense: mit\n---\n# PushT\n\nAuthor notes.\n"
    out = merge_card_into_readme(readme, CARD)
    assert out.startswith(readme.rstrip())
    assert "body" in out


def test_merge_replaces_marked_section_only():
    readme = f"# Intro\n\n{_CARD_START}\nold card\n{_CARD_END}\n\n## Citation\n\ncite me\n"
    out = merge_card_into_readme(readme, CARD)
    assert "old card" not in out
    assert out.count(_CARD_START) == 1
    assert "## Citation\n\ncite me" in out
    assert out.index("# Intro") < out.index(_CARD_START) < out.index("## Citation")


def test_merge_is_idempotent():
    once = merge_card_into_readme("# Intro\n", CARD)
    assert merge_card_into_readme(once, CARD) == once


def test_merge_upgrades_legacy_card_without_dropping_trailing_content():
    legacy = (
        "# Intro\n\n## Dataset Quality Report (Calibra v0.9.0)\n\nold\n\n---\n"
        "_Generated by [Calibra](https://x) v0.9.0_\n\n## Citation\n\ncite me\n"
    )
    out = merge_card_into_readme(legacy, CARD)
    assert "v0.9.0" not in out
    assert "## Citation\n\ncite me" in out
    assert out.count("## Dataset Quality Report") == 1


@pytest.fixture
def fake_hub(monkeypatch, tmp_path):
    """Install a stub huggingface_hub so push_to_hub runs offline."""
    readme = tmp_path / "README.md"
    readme.write_text("# Existing\n\nKeep me.\n", encoding="utf-8")

    class EntryNotFoundError(Exception):
        pass

    api = MagicMock()
    api.upload_file.return_value = types.SimpleNamespace(pr_url="https://hf.co/pr/1")
    hub = types.ModuleType("huggingface_hub")
    hub.HfApi = lambda: api
    hub.hf_hub_download = MagicMock(return_value=str(readme))
    utils = types.ModuleType("huggingface_hub.utils")
    utils.EntryNotFoundError = EntryNotFoundError
    monkeypatch.setitem(sys.modules, "huggingface_hub", hub)
    monkeypatch.setitem(sys.modules, "huggingface_hub.utils", utils)
    return types.SimpleNamespace(api=api, hub=hub, EntryNotFoundError=EntryNotFoundError)


def test_push_keeps_existing_readme(fake_hub):
    push_to_hub(CARD, "org/ds")
    kwargs = fake_hub.api.upload_file.call_args.kwargs
    body = kwargs["path_or_fileobj"].decode()
    assert "Keep me." in body and "body" in body
    assert kwargs["create_pr"] is False
    assert kwargs["repo_type"] == "dataset"


def test_push_create_pr(fake_hub, capsys):
    push_to_hub(CARD, "lerobot/pusht", create_pr=True)
    assert fake_hub.api.upload_file.call_args.kwargs["create_pr"] is True
    assert "https://hf.co/pr/1" in capsys.readouterr().out


def test_push_without_readme_creates_one(fake_hub):
    fake_hub.hub.hf_hub_download.side_effect = fake_hub.EntryNotFoundError()
    push_to_hub(CARD, "org/ds")
    body = fake_hub.api.upload_file.call_args.kwargs["path_or_fileobj"].decode()
    assert body.startswith(_CARD_START)


def test_push_aborts_when_readme_unreadable(fake_hub):
    fake_hub.hub.hf_hub_download.side_effect = OSError("network down")
    with pytest.raises(SystemExit):
        push_to_hub(CARD, "org/ds")
    fake_hub.api.upload_file.assert_not_called()
